"""SSH transport using the system OpenSSH client.

- Honours ~/.ssh/config (aliases, keys, agent, ProxyJump, NVIDIA Sync entries).
- Host keys are always verified (StrictHostKeyChecking=yes). The user's own
  known_hosts settings are left alone; keys trusted through Newton live in a
  separate file added as a global known_hosts file. New keys are only ever
  *captured* (KnownHostsCommand records what the host presents, which works through
  ProxyCommand/Tailscale aliases too) and trusted after the user approves them.
- Scripted connections neutralise ~/.ssh/config options that would make them
  interactive, multiplexed or forwarding more than asked (RemoteCommand, RequestTTY,
  ControlMaster, ForwardAgent, LocalForward...).
- Remote commands are fixed strings defined in this module; the only variable
  parts are validated integers, agentd-generated hex stage names and shlex-quoted
  settings. Nothing model-generated ever reaches a remote shell.
- Job traffic goes over an `ssh -N -L` tunnel to the worker's HTTP API, which
  listens on a Unix socket in ~/.newton (0700): only its owner can reach it.
"""

